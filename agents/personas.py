PERSONAS = {
    "default": DEFAULT,
    "vuln": VULNERABLE,
    "safe": HARDENED,
}

PERSONA_DESCRIPTIONS = {
    "default": "обычный Jarvis",
    "vuln": "поддержка TaskFlow, промпт-жертва (день 46)",
    "safe": "поддержка TaskFlow, защищённый промпт (день 46)",
}


def resolve_persona_name(system_prompt: str) -> str:
    """Возвращает имя персоны по тексту промпта; 'custom', если совпадений нет."""
    for name, prompt in PERSONAS.items():
        if prompt == system_prompt:
            return name
    return "custom"

def render_file_read(tool: str = "", paths: list[str] | None = None) -> list[list[str]]:
    """Возвращает шаги file_read с подставленными путями-кандидатами."""
    paths = paths or PATH_GUESSES
    steps: list[list[str]] = []
    for seq in SEEDS["file_read"]:
        if any("{path}" in s for s in seq):
            for p in paths:
                steps.append([s.replace("{path}", p) for s in seq])
        else:
            steps.append(list(seq))
    return steps
